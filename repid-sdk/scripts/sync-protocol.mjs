// Copies the normative files from the protocol repository into src/protocol/.
//
// Run after changing the protocol. `check-drift` then fails until this is run,
// which is the point: the protocol is the single source of truth and the SDK
// must not be able to quietly disagree with it.

import path from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';
import {
  SDK_ROOT,
  SYNCED_FILES,
  resolveProtocolRepo,
  readSourceFile,
  sha256,
  writeManifest,
} from './lib/sync-common.mjs';

const protocolRepo = resolveProtocolRepo();
const entries = [];

for (const { source, dest, label } of SYNCED_FILES) {
  const bytes = readSourceFile(protocolRepo, source);
  if (!bytes) {
    console.error(`FATAL: ${label} not found at ${path.join(protocolRepo, source)}`);
    console.error('       set REPID_PROTOCOL_REPO to the protocol repository checkout.');
    process.exit(1);
  }

  const absoluteDest = path.join(SDK_ROOT, dest);
  mkdirSync(path.dirname(absoluteDest), { recursive: true });
  writeFileSync(absoluteDest, bytes);

  entries.push({ source, dest, label, sha256: sha256(bytes) });
  console.log(`synced  ${label.padEnd(22)} ${source} -> ${dest}`);
}

writeManifest({
  protocolRepository: 'repid-protocol',
  note:
    'Generated by scripts/sync-protocol.mjs. Do not edit by hand: these files are ' +
    'normative inputs copied from the repid-protocol repository, and ' +
    'scripts/check-drift.mjs compares them against it. The location of that ' +
    'checkout is deliberately not recorded here: it is resolved from ' +
    'REPID_PROTOCOL_REPO or from the sibling directory at check time, so this ' +
    'file stays valid on any machine and in a published package.',
  files: entries,
});

console.log(`\n${entries.length} files synced. Manifest written to SOURCE.json.`);
